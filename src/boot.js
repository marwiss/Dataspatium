    const chosen = known(asked) || known(stored) || known(env ? env.preset : configLanguage());
    if (chosen) return withEnglish(chosen);
    const prefs = env ? env.prefs : (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'sv']);
