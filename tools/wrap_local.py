#!/usr/bin/env python3
"""Embed Dataspatium's own non-JavaScript files (R helpers, example data) as asset wrappers.

Pages opened via file:// cannot fetch() local files, so text files the app needs at runtime are
wrapped as JavaScript next to the original and declared in presets/local-assets.js.

Usage:
    python tools/wrap_local.py
"""
import base64
import gzip
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOCAL_FILES = [
    "r/dataspatium.R",
    "presets/exempeldata/befolkning-kommuner-2024.csv",
]
LOCAL_GLOBS = [
    "presets/geo/*.geojson",
    "presets/api/*.api.json",
]
# Larger text files travel gzip+base64 (platform/assets gunzips them with DecompressionStream): the plan catalogue.
LOCAL_GZIP_GLOBS = [
    "presets/plan/*.json",
]
MANIFEST = ROOT / "presets" / "local-assets.js"


def main():
    entries = {}
    files = list(LOCAL_FILES) + sorted(p.relative_to(ROOT).as_posix() for g in LOCAL_GLOBS for p in ROOT.glob(g))
    for rel in files:
        src = ROOT / rel
        text = src.read_text(encoding="utf-8")
        wrapper = src.with_name(src.name + ".js")
        wrapper.write_text(
            f"// Generated by tools/wrap_local.py from {rel}. Do not edit; edit the original.\n"
            f"Dataspatium.assets.register({json.dumps(rel)},\"text\",{json.dumps(text, ensure_ascii=False)});\n",
            encoding="utf-8", newline="\n")
        entries[rel] = {"file": wrapper.relative_to(ROOT).as_posix(), "encoding": "text", "size": len(text.encode("utf-8")), "library": "dataspatium"}
        print(f"  wrote {wrapper.relative_to(ROOT).as_posix()}")
    for rel in sorted(p.relative_to(ROOT).as_posix() for g in LOCAL_GZIP_GLOBS for p in ROOT.glob(g)):
        src = ROOT / rel
        data = src.read_bytes()
        wrapper = src.with_name(src.name + ".js")
        payload = base64.b64encode(gzip.compress(data, compresslevel=9, mtime=0)).decode("ascii")
        wrapper.write_text(
            f"// Generated by tools/wrap_local.py from {rel} (gzip+base64). Do not edit; edit the original.\n"
            f"Dataspatium.assets.register({json.dumps(rel)},\"gzip+base64\",\"{payload}\");\n",
            encoding="utf-8", newline="\n")
        entries[rel] = {"file": wrapper.relative_to(ROOT).as_posix(), "encoding": "gzip+base64", "size": len(data), "library": "dataspatium"}
        print(f"  wrote {wrapper.relative_to(ROOT).as_posix()} ({len(data)} bytes, gzip)")
    MANIFEST.write_text(
        "// Generated by tools/wrap_local.py. Declares Dataspatium's own embedded text assets.\n"
        "Dataspatium.assets.addEntries(" + json.dumps(entries, indent=1, ensure_ascii=False) + ");\n",
        encoding="utf-8", newline="\n")
    print(f"  wrote {MANIFEST.relative_to(ROOT).as_posix()} ({len(entries)} assets)")


if __name__ == "__main__":
    main()
