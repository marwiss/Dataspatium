#!/usr/bin/env python3
"""Embed Dataspatium's own non-JavaScript files (R helpers, example data, the handbook) as asset wrappers.

Pages opened via file:// cannot fetch() local files, so text files the app needs at runtime are
wrapped as JavaScript next to the original and declared in presets/local-assets.js. The user
documentation is bundled per language as docs/help/<lang>.js for the help panel (ui/help); the
asset names are docs/<lang>/<name>.md for every language, Swedish included.

Usage:
    python tools/wrap_local.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
LOCAL_FILES = [
    "r/dataspatium.R",
    "python/dataspatium.py",
    "presets/exempeldata/befolkning-kommuner-2024.csv",
]
LOCAL_GLOBS = [
    "presets/geo/*.geojson",
    "presets/api/*.api.json",
]
# The handbook shown by ui/help: user documents in reading order (same list as DOCS in src/ui/help/help-panel.js).
# Swedish lives in docs/, the other languages in docs/<lang>/. Developer documents are not embedded.
HELP_DOCS = [
    "kom-igang", "anvandarguide", "lagen", "soka", "bearbeta", "visualisera", "anteckningsbok", "regex",
    "format", "api-konfiguration", "kallor", "r-guide", "python", "dokument", "dokumentmallar", "dela", "mobil", "faq", "licenser",
]
HELP_LANGS = ["sv", "da", "nb", "fi", "is", "en"]
MANIFEST = ROOT / "presets" / "local-assets.js"


def register_line(name, text):
    return f"Dataspatium.assets.register({json.dumps(name)},\"text\",{json.dumps(text, ensure_ascii=False)});\n"


def main():
    entries = {}
    files = list(LOCAL_FILES) + sorted(p.relative_to(ROOT).as_posix() for g in LOCAL_GLOBS for p in ROOT.glob(g))
    for rel in files:
        src = ROOT / rel
        text = src.read_text(encoding="utf-8")
        wrapper = src.with_name(src.name + ".js")
        wrapper.write_text(
            f"// Generated by tools/wrap_local.py from {rel}. Do not edit; edit the original.\n" + register_line(rel, text),
            encoding="utf-8", newline="\n")
        entries[rel] = {"file": wrapper.relative_to(ROOT).as_posix(), "encoding": "text", "size": len(text.encode("utf-8")), "library": "dataspatium"}
        print(f"  wrote {wrapper.relative_to(ROOT).as_posix()}")
    help_dir = ROOT / "docs" / "help"
    help_dir.mkdir(exist_ok=True)
    for lang in HELP_LANGS:
        folder = "docs/" if lang == "sv" else f"docs/{lang}/"
        lines = [f"// Generated by tools/wrap_local.py from {folder}*.md. Do not edit; edit the originals.\n"]
        for doc in HELP_DOCS:
            text = (ROOT / folder / f"{doc}.md").read_text(encoding="utf-8")
            name = f"docs/{lang}/{doc}.md"
            lines.append(register_line(name, text))
            entries[name] = {"file": f"docs/help/{lang}.js", "encoding": "text", "size": len(text.encode("utf-8")), "library": "dataspatium"}
        out = help_dir / f"{lang}.js"
        out.write_text("".join(lines), encoding="utf-8", newline="\n")
        print(f"  wrote {out.relative_to(ROOT).as_posix()} ({len(HELP_DOCS)} documents)")
    MANIFEST.write_text(
        "// Generated by tools/wrap_local.py. Declares Dataspatium's own embedded text assets.\n"
        "Dataspatium.assets.addEntries(" + json.dumps(entries, indent=1, ensure_ascii=False) + ");\n",
        encoding="utf-8", newline="\n")
    print(f"  wrote {MANIFEST.relative_to(ROOT).as_posix()} ({len(entries)} assets)")


if __name__ == "__main__":
    main()
