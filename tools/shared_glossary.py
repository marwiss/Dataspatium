"""Excerpts of the seven dictionaries src/ui/i18n/<lang>.js, so the app's own translations are the source:

- the shared glossary, the words Dataspatium and Dataregium have in common, as presets/i18n-shared.json. The keys are listed in
  presets/shared-keys.txt (one per line, # comments), and Dataregium compares its files against the JSON;
- the first-start chooser's words in every language (CHOOSER_KEYS), as src/ui/i18n/languages.js. The very first start loads that
  small file and the browser language's dictionary instead of all seven (src/boot.js);
- the English texts of the keys that one of the other five languages lacks, with the singular (`.one`) of each, as
  src/ui/i18n/en-missing.js. The start loads it with those languages in place of all of en.js (src/boot.js), so run the tool
  after adding keys.

New texts are written in Swedish and English only (F49 a): those two must have every key, and a key another language lacks
takes the English text there, as the app shows it (ui/i18n).

Run from the repo root; --check fails when a file on disk differs from what the i18n files give (CI, tests and every release)."""
from __future__ import annotations

import io
import json
import re
import sys

LANGS = ['sv', 'en', 'da', 'nb', 'nn', 'fi', 'is']
KEYS_FILE = 'presets/shared-keys.txt'
OUT = 'presets/i18n-shared.json'
LINE = re.compile(r"^\s*'([^']+)':\s*'((?:[^'\\]|\\.)*)',?\s*$", re.M)
# The first-start chooser (chooseLanguage in src/ui/shell/shell.js): its title, hint, keep button and the list's name.
CHOOSER_LANGS = ['sv', 'da', 'nb', 'nn', 'fi', 'is', 'en']
CHOOSER_KEYS = ['lang.title', 'lang.first.title', 'lang.first.hint', 'lang.first.keep']
CHOOSER_OUT = 'src/ui/i18n/languages.js'
# The languages that must have every key; the others fall back to English (FALLBACK).
COMPLETE = ['sv', 'en']
FALLBACK = 'en'
# The English texts the other languages lack (src/boot.js FALLBACK_EN loads it with them).
MISSING_OUT = 'src/ui/i18n/en-missing.js'


def raw_lang(lang: str) -> dict[str, str]:
    """Each key's string literal as written in the dictionary (between the single quotes, escapes kept)."""
    text = io.open(f'src/ui/i18n/{lang}.js', encoding='utf-8').read()
    return {m.group(1): m.group(2) for m in LINE.finditer(text)}


def load_lang(lang: str) -> dict[str, str]:
    return {k: v.replace("\\'", "'").replace('\\\\', '\\') for k, v in raw_lang(lang).items()}


def with_fallback(langs: dict[str, dict[str, str]], wanted: list[str]) -> dict[str, dict[str, str]]:
    """Every wanted key in every language: Swedish and English must have it, the others take English where they lack it."""
    missing = [(lang, k) for lang in COMPLETE for k in wanted if k not in langs[lang]]
    if missing:
        raise SystemExit('missing in i18n files: ' + ', '.join(f'{l}:{k}' for l, k in missing[:20]))
    return {lang: {k: d[k] if k in d else langs[FALLBACK][k] for k in wanted} for lang, d in langs.items()}


def keys() -> list[str]:
    lines = io.open(KEYS_FILE, encoding='utf-8').read().splitlines()
    return [l.strip() for l in lines if l.strip() and not l.strip().startswith('#')]


def build() -> dict:
    wanted = keys()
    langs = with_fallback({lang: load_lang(lang) for lang in LANGS}, wanted)
    return {
        'name': 'Dataspatium and Dataregium shared glossary',
        'version': 1,
        'source': 'Dataspatium src/ui/i18n/<lang>.js, chosen by presets/shared-keys.txt; regenerate with python tools/shared_glossary.py',
        'languages': LANGS,
        'keys': {k: {lang: langs[lang][k] for lang in LANGS} for k in wanted},
    }


def build_chooser() -> str:
    """src/ui/i18n/languages.js: the module i18n/languages, {code: {key: text}} for the chooser's keys."""
    raw = with_fallback({lang: raw_lang(lang) for lang in CHOOSER_LANGS}, CHOOSER_KEYS)
    lines = [
        '// @ts-check',
        '// SPDX-License-Identifier: LicenseRef-PolyForm-Strict-1.0.0',
        '// Generated by tools/shared_glossary.py from src/ui/i18n/<lang>.js. Do not edit; edit the dictionaries and run the tool.',
        '/**',
        " * The first-start language chooser's words in each of the seven languages. The very first start loads this file and the",
        " * browser language's dictionary, not all seven (src/boot.js), and the chooser shows each language in itself (ui/i18n tIn).",
        ' */',
        '(function () {',
        "  'use strict';",
        '  const D = globalThis.Dataspatium;',
        "  D.define('i18n/languages', [], () => ({",
    ]
    for lang in CHOOSER_LANGS:
        lines.append(f"    '{lang}': {{")
        lines.extend(f"      '{k}': '{raw[lang][k]}'," for k in CHOOSER_KEYS)
        lines.append('    },')
    lines += ['  }));', '})();', '']
    return '\n'.join(lines)


def build_missing() -> tuple[str, int]:
    """src/ui/i18n/en-missing.js: the module i18n/en-missing, {key: text} in en.js's order for the keys of English that one of
    the languages outside COMPLETE lacks, each with its singular `.one` when English has one; and the number of keys."""
    en = raw_lang(FALLBACK)
    others = [raw_lang(lang) for lang in LANGS if lang not in COMPLETE]
    lacked = {k for d in others for k in en if k not in d}
    lacked |= {k + '.one' for k in lacked if k + '.one' in en}
    keys = [k for k in en if k in lacked]
    lines = [
        '// @ts-check',
        '// SPDX-License-Identifier: LicenseRef-PolyForm-Strict-1.0.0',
        '// Generated by tools/shared_glossary.py from src/ui/i18n/<lang>.js. Do not edit; edit the dictionaries and run the tool.',
        '/**',
        " * The English texts of the keys that Danish, Norwegian (bokmål, nynorsk), Finnish or Icelandic lacks (new texts are written",
        " * in Swedish and English only, F49 a). The start loads this file with those languages in place of all of en.js (src/boot.js),",
        " * ui/i18n shows these texts where the translation lacks one, and a key missing here too loads en.js.",
        ' */',
        '(function () {',
        "  'use strict';",
        '  const D = globalThis.Dataspatium;',
        "  D.define('i18n/en-missing', [], () => ({",
    ]
    lines.extend(f"    '{k}': '{en[k]}'," for k in keys)
    lines += ['  }));', '})();', '']
    return '\n'.join(lines), len(keys)


def main(argv: list[str]) -> int:
    data = build()
    missing, missing_keys = build_missing()
    outputs = [
        (OUT, json.dumps(data, ensure_ascii=False, indent=1) + '\n', f'{len(data["keys"])} keys in {len(LANGS)} languages'),
        (CHOOSER_OUT, build_chooser(), f'{len(CHOOSER_KEYS)} keys in {len(CHOOSER_LANGS)} languages'),
        (MISSING_OUT, missing, f'{missing_keys} English keys that {", ".join(l for l in LANGS if l not in COMPLETE)} lack'),
    ]
    if '--check' in argv:
        stale = 0
        for path, text, what in outputs:
            try:
                current = io.open(path, encoding='utf-8').read()
            except OSError:
                current = ''
            if current != text:
                print(f'{path} differs from the i18n files; run python tools/shared_glossary.py')
                stale += 1
            else:
                print(f'{path} is current ({what})')
        return 1 if stale else 0
    for path, text, what in outputs:
        io.open(path, 'w', encoding='utf-8', newline='\n').write(text)
        print(f'wrote {path}: {what}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
